"""Build the evidence package for Reviewer 6, item R6-02.

The flat-text results are reused from the leakage-audited R3-03 five-fold
experiment.  The InLegalLlama rows are recomputed from per-case generations:
unparseable outputs are abstentions and count as errors in the primary metrics.
Parsed-only performance is retained under the explicit name ``selective``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


HERE = Path(__file__).resolve().parent
PAPER_TESTS = HERE.parents[1]
REPO = HERE.parents[2]
R3_OUTPUTS = PAPER_TESTS / "codes" / "R3_03_non_llm_baselines" / "outputs"
LLM_OUTPUTS = REPO / "model comparison" / "outputs"
HGT_KFOLD = (
    REPO
    / "section_GNN/outputs/ablations/entity_resolved_data/cross_bucket_total_dataset/models"
    / "ablation_entity_resolved_section_sep_lr_decay_cross_bucket_kfold/kfold/kfold_summary.json"
)
LLM_RUNS = {
    "InLegalLlama (CPT)": (
        "lnlproc_inlegalllama_entity_resolved_section_sep_lr_decay_cross_bucket_fold00_test"
    ),
    "InLegalLlama (SFT)": (
        "lnlproc_inlegalllama_sft_pred_only_original_prompt_cross_bucket_fold00"
    ),
}
LABELS = ("-1", "1")
OUTPUTS = HERE / "outputs"


def per_label(rows: list[dict[str, Any]], label: str) -> dict[str, float | int]:
    tp = sum(r["true_label"] == label and r.get("predicted_label") == label for r in rows)
    fp = sum(r["true_label"] != label and r.get("predicted_label") == label for r in rows)
    fn = sum(r["true_label"] == label and r.get("predicted_label") != label for r in rows)
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {"tp": tp, "fp": fp, "fn": fn, "precision": precision, "recall": recall, "f1": f1}


def evaluate_llm(run_dir: Path) -> dict[str, Any]:
    rows = []
    with (run_dir / "combined_predictions.jsonl").open(encoding="utf-8") as handle:
        for line in handle:
            row = json.loads(line)
            if str(row.get("true_label")) in LABELS:
                row["true_label"] = str(row["true_label"])
                prediction = row.get("predicted_label")
                row["predicted_label"] = str(prediction) if prediction is not None else None
                rows.append(row)

    answered = [r for r in rows if r.get("predicted_label") in LABELS]
    correct = sum(r["true_label"] == r.get("predicted_label") for r in rows)
    strict = {label: per_label(rows, label) for label in LABELS}
    selective = {label: per_label(answered, label) for label in LABELS}
    result = {
        "n": len(rows),
        "answered": len(answered),
        "abstained": len(rows) - len(answered),
        "coverage": len(answered) / len(rows),
        "accuracy": correct / len(rows),
        "macro_f1": sum(v["f1"] for v in strict.values()) / len(LABELS),
        "selective_accuracy": correct / len(answered),
        "selective_macro_f1": sum(v["f1"] for v in selective.values()) / len(LABELS),
        "per_label": strict,
        "selective_per_label": selective,
        "policy": "full denominator; unparseable generations are abstentions counted as errors",
    }
    recorded = json.loads((run_dir / "metrics.json").read_text())
    for key in ("accuracy", "macro_f1", "selective_accuracy", "selective_macro_f1", "coverage"):
        if abs(result[key] - recorded[key]) > 1e-12:
            raise AssertionError(f"{run_dir.name}: recomputed {key} differs from metrics.json")
    return result


