def main() -> None:
    summary = json.loads((R3_OUTPUTS / "baselines_summary.json").read_text())
    baselines = summary["baselines"]
    hgt = json.loads(HGT_KFOLD.read_text())["aggregate"]
    payload = {
        "task_id": "R6-02",
        "status": "resolved",
        "flat_text": {
            "n": summary["n_cases"],
            "folds": summary["k"],
            "majority": {
                "accuracy": baselines["B0_majority"]["aggregate"]["accuracy_mean"],
                "macro_f1": baselines["B0_majority"]["aggregate"]["macro_f1_mean"],
            },
            "svm": {
                "accuracy": baselines["B3_svm_tfidf"]["aggregate"]["accuracy_mean"],
                "macro_f1": baselines["B3_svm_tfidf"]["aggregate"]["macro_f1_mean"],
            },
            "logreg": {
                "accuracy": baselines["B4_logreg_tfidf"]["aggregate"]["accuracy_mean"],
                "macro_f1": baselines["B4_logreg_tfidf"]["aggregate"]["macro_f1_mean"],
            },
            "source": str(R3_OUTPUTS / "baselines_summary.json"),
        },
        "hgt": {
            "accuracy": hgt["accuracy_mean"],
            "macro_f1": hgt["macro_f1_mean"],
            "source": str(HGT_KFOLD),
        },
        "llm": {
            label: evaluate_llm(LLM_OUTPUTS / directory)
            for label, directory in LLM_RUNS.items()
        },
    }
    OUTPUTS.mkdir(exist_ok=True)
    (OUTPUTS / "r6_02_results.json").write_text(json.dumps(payload, indent=2) + "\n")
    (OUTPUTS / "table_r6_02.tex").write_text(latex(payload))
    (OUTPUTS / "report_r6_02.md").write_text(report(payload))
    print(f"wrote R6-02 evidence package to {OUTPUTS}")


if __name__ == "__main__":
    main()
